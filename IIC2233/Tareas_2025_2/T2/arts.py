def corazon_dcc():
    patron = "dcc-"
    for y in range(14, -14, -1):
        linea = ""
        for x in range(-14, 14):
            a = x / 10.0
            b = y / 10.0
            if (a * a + b * b - 1) ** 3 - a * a * (b ** 3) <= 0:
                linea += patron
            else:
                linea += " " * len(patron)
        print(linea.rstrip())


